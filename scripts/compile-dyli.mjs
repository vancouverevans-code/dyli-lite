import { readFileSync, writeFileSync } from "node:fs";
import solc from "solc";

const source = readFileSync(new URL("../contracts/DyliLite.sol", import.meta.url), "utf8");
const input = {
  language: "Solidity",
  sources: { "DyliLite.sol": { content: source } },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: "paris",
    outputSelection: {
      "*": {
        "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object", "evm.methodIdentifiers"],
      },
    },
  },
};

const out = JSON.parse(solc.compile(JSON.stringify(input)));
if (out.errors?.some((e) => e.severity === "error")) {
  console.error(out.errors);
  process.exit(1);
}
for (const e of out.errors ?? []) {
  if (e.severity !== "error") console.error(e.formattedMessage);
}

const contract = out.contracts["DyliLite.sol"].DyliLite;
const creation = contract.evm.bytecode.object;
const runtime = contract.evm.deployedBytecode.object;
if (!creation || !runtime) {
  console.error("missing bytecode");
  process.exit(1);
}

const runtimeBytes = runtime.length / 2;
const creationBytes = creation.length / 2;
const limit = 24576;
console.log(`creation ${creationBytes} bytes`);
console.log(`runtime  ${runtimeBytes} bytes  (${((runtimeBytes / limit) * 100).toFixed(1)}% of 24KB)`);
if (runtimeBytes > limit) {
  console.error("runtime exceeds EIP-170");
  process.exit(1);
}

const ids = contract.evm.methodIdentifiers;
const need = [
  "shelf()",
  "claim(uint256)",
  "list(uint256,uint256)",
  "cancel(uint256)",
  "buy(uint256)",
  "redeem(uint256)",
  "faucet()",
  "balanceOf(address)",
  "lastFaucet(address)",
  "feeTo()",
  "held(address)",
];
const selectors = {};
for (const sig of need) {
  if (!ids[sig]) {
    console.error("missing selector", sig, ids);
    process.exit(1);
  }
  const key = sig.slice(0, sig.indexOf("("));
  selectors[key] = "0x" + ids[sig];
}

const file = `/* Generated by scripts/compile-dyli.mjs. Do not edit. */
export const CREATION_BYTES = ${creationBytes};
export const RUNTIME_BYTES = ${runtimeBytes};
export const EIP170_LIMIT = ${limit};
export const SELECTORS = ${JSON.stringify(selectors, null, 2)} as const;
export const CREATION_BYTECODE = "0x${creation}";
`;

writeFileSync(new URL("../src/lib/dyli/artifact.ts", import.meta.url), file);
console.log(selectors);
